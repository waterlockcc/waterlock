import type { Operation, OperationTable, ParamSpec } from "../core/types.js";
import type { CodegenConfig } from "./config.js";
import { assignGroups, type GroupResult } from "./groups.js";
import type { NormalizedSpec } from "./model.js";

export interface GenerateResult {
  code: string;
  report: string;
  table: OperationTable;
}

export function generate(spec: NormalizedSpec, config: CodegenConfig): GenerateResult {
  const grouping = assignGroups(spec.operations, config);

  const operations: Operation[] = spec.operations.flatMap((op) =>
    op.routes.map((route) => ({
      action: op.action,
      method: op.method,
      path: route.path,
      variant: route.variant,
      params: op.params,
      hasBody: op.hasBody,
      groups: grouping.byAction.get(op.action)!.groups,
    })),
  );

  const table: OperationTable = {
    provider: config.provider,
    source: {
      kind: spec.kind,
      title: spec.title,
      version: spec.version,
      ...(spec.revision ? { revision: spec.revision } : {}),
      ...(config.source.url ? { url: config.source.url } : {}),
    },
    globalQueryParams: spec.globalQueryParams,
    operations,
  };

  return { code: emitCode(spec, config, table), report: emitReport(spec, config, grouping, operations), table };
}

// ---------------------------------------------------------------------------
// TS emitter. One operation per line so spec updates produce readable diffs.

function emitCode(spec: NormalizedSpec, config: CodegenConfig, table: OperationTable): string {
  const P = config.typePrefix;
  const actions = spec.operations.map((o) => o.action);
  const groups = [...new Set(table.operations.flatMap((o) => o.groups))].sort();
  const tableName = `${config.provider}Table`;
  const typesImport = config.typesImport ?? "@waterlock/gateway";

  const out: string[] = [];
  out.push(
    `// GENERATED by waterlock codegen. Do not edit by hand.`,
    `// Source: ${spec.title} ${spec.version}${spec.revision ? ` (revision ${spec.revision})` : ""}`,
    `// Curate groups in ${config.provider}.config.ts, then regenerate.`,
    ``,
    `import type { OperationTable } from ${JSON.stringify(typesImport)};`,
    ``,
    `export type ${P}Action =`,
    ...actions.map((a, i) => `  | ${JSON.stringify(a)}${i === actions.length - 1 ? ";" : ""}`),
    ``,
    `export type ${P}Group =`,
    ...groups.map((g, i) => `  | ${JSON.stringify(g)}${i === groups.length - 1 ? ";" : ""}`),
    ``,
    `/** Typed path + query params per action, as seen by policy rules. */`,
    `export interface ${P}Params {`,
  );
  for (const op of spec.operations) {
    if (op.params.length === 0) {
      out.push(`  ${JSON.stringify(op.action)}: Record<string, never>;`);
      continue;
    }
    out.push(`  ${JSON.stringify(op.action)}: {`);
    for (const p of op.params) {
      const optional = p.in === "path" || p.required ? "" : "?";
      out.push(`    ${JSON.stringify(p.name)}${optional}: ${tsType(p)};`);
    }
    out.push(`  };`);
  }
  out.push(`}`, ``);

  out.push(
    `export const ${tableName}: OperationTable = {`,
    `  provider: ${JSON.stringify(table.provider)},`,
    `  source: ${JSON.stringify(table.source)},`,
    `  globalQueryParams: [`,
    ...table.globalQueryParams.map((p) => `    ${JSON.stringify(p)},`),
    `  ],`,
    `  operations: [`,
    ...table.operations.map((o) => `    ${JSON.stringify(o)},`),
    `  ],`,
    `};`,
    ``,
  );
  return out.join("\n");
}

function tsType(p: ParamSpec): string {
  const base = p.enum
    ? p.enum.map((e) => JSON.stringify(e)).join(" | ")
    : p.type === "integer" || p.type === "number"
      ? "number"
      : p.type;
  if (!p.repeated) return base;
  return p.enum ? `(${base})[]` : `${base}[]`;
}

// ---------------------------------------------------------------------------
// Review report: what a human must look at when the spec or curation changes.

function emitReport(spec: NormalizedSpec, config: CodegenConfig, grouping: GroupResult, ops: Operation[]): string {
  const lines: string[] = [];
  const variants = ops.filter((o) => o.variant !== "standard");
  lines.push(
    `# ${config.provider} codegen report`,
    ``,
    `Source: ${spec.title} ${spec.version}${spec.revision ? `, revision ${spec.revision}` : ""}`,
    ``,
    `- ${spec.operations.length} actions, ${ops.length} routes (${variants.length} upload/resumable variants)`,
    `- ${[...grouping.byAction.values()].filter((g) => g.source === "fallback").length} actions grouped by fallback heuristic`,
    `- ${grouping.unusedPatterns.length} curated patterns matched nothing`,
    ``,
  );

  if (grouping.unusedPatterns.length) {
    lines.push(`## Curated patterns that matched nothing`, ``, `Spec probably renamed or removed these. Fix the config.`, ``);
    for (const u of grouping.unusedPatterns) lines.push(`- \`${u.group}\`: \`${u.pattern}\``);
    lines.push(``);
  }

  const fallback = spec.operations.filter((o) => grouping.byAction.get(o.action)!.source === "fallback");
  if (fallback.length) {
    lines.push(`## Grouped by fallback (review these)`, ``, `| action | method | groups |`, `|---|---|---|`);
    for (const o of fallback) {
      lines.push(`| \`${o.action}\` | ${o.method} | ${grouping.byAction.get(o.action)!.groups.join(", ")} |`);
    }
    lines.push(``);
  }

  lines.push(`## Groups`, ``);
  const groups = [...new Set(ops.flatMap((o) => o.groups))].sort();
  for (const g of groups) {
    const members = spec.operations.filter((o) => grouping.byAction.get(o.action)!.groups.includes(g));
    lines.push(`### \`${g}\` (${members.length})`, ``);
    for (const o of members) {
      const extra = o.routes.filter((r) => r.variant !== "standard").map((r) => `+${r.variant}`);
      const tag = grouping.byAction.get(o.action)!.source === "fallback" ? " _(fallback)_" : "";
      lines.push(`- \`${o.action}\` ${o.method} \`${o.routes[0]!.path}\`${extra.length ? ` ${extra.join(" ")}` : ""}${tag}`);
    }
    lines.push(``);
  }

  if (variants.length) {
    lines.push(
      `## Alternate routes`,
      ``,
      `Each of these reaches the same action as its standard route. The gateway matches them,`,
      `so policy applies, but body decoders only handle the standard variant.`,
      ``,
    );
    for (const v of variants) lines.push(`- \`${v.action}\` ${v.variant}: ${v.method} \`${v.path}\``);
    lines.push(``);
  }

  return lines.join("\n");
}
